const STORAGE_KEY = 'atlas.language.v1';
const LANGS = ['es','en','pt'];
function initialLocale() {
  try { const saved = localStorage.getItem(STORAGE_KEY); if (LANGS.includes(saved)) return saved; } catch (_) {}
  for (const lang of (navigator.languages || [navigator.language || 'es'])) {
    const normalized = String(lang).toLowerCase().split('-')[0];
    if (LANGS.includes(normalized)) return normalized;
  }
  return 'es';
}
let activeLocale = initialLocale();
const localeTags = {es:'es-AR',en:'en-US',pt:'pt-BR'};
export function getLocale() {return activeLocale;}
export function getLocaleTag() {return localeTags[activeLocale];}
export function t(key,params={}) {
  const value = MESSAGES[activeLocale][key] ?? MESSAGES.es[key];
  if (value === undefined) { console.warn('When buy missing translation:',key); return key; }
  return value.replace(/\{([a-zA-Z]+)\}/g,(_,variable)=>String(params[variable] ?? ''));
}
export function formatNumber(value,options={}) {return new Intl.NumberFormat('en-US',options).format(value);}
export function formatDate(date,options={}) {return new Intl.DateTimeFormat(getLocaleTag(),options).format(date);}
function nonEmptyTextNodes(element) {
  return Array.from(element.childNodes).filter(node=>node.nodeType===Node.TEXT_NODE && node.nodeValue.trim());
}
function replaceNode(element,key,index=0) {
  const target=nonEmptyTextNodes(element)[index];
  if (!target) return;
  // Keep original spacing around labels and decorative icons.
  const prefix=/^\s*/.exec(target.nodeValue)?.[0] || '';
  const suffix=/\s*$/.exec(target.nodeValue)?.[0] || '';
  const value = t(key);
  target.nodeValue = prefix + value + suffix;
}
export function translateStatic() {
  document.documentElement.lang = getLocaleTag();
  for (const element of document.querySelectorAll('[data-i18n]')) element.textContent=t(element.dataset.i18n);
  for (const element of document.querySelectorAll('[data-i18n-node]')) {
    if (element.hasAttribute('data-i18n-nodes')) continue;
    replaceNode(element,element.dataset.i18nNode);
  }
  for (const element of document.querySelectorAll('[data-i18n-nodes]')) {
    const keys=element.dataset.i18nNodes.split('|');
    keys.forEach((key,i)=>replaceNode(element,key,i));
  }
  for (const element of document.querySelectorAll('[data-i18n-aria-label]')) element.setAttribute('aria-label',t(element.dataset.i18nAriaLabel));
  for (const element of document.querySelectorAll('[data-i18n-title]')) element.setAttribute('title',t(element.dataset.i18nTitle));
  for (const element of document.querySelectorAll('[data-i18n-placeholder]')) element.setAttribute('placeholder',t(element.dataset.i18nPlaceholder));
  for (const element of document.querySelectorAll('[data-i18n-content]')) element.setAttribute('content',t(element.dataset.i18nContent));
  for(const select of document.querySelectorAll('[data-language-select]')) select.value=activeLocale;
}
export function setLocale(locale) {
  if (!LANGS.includes(locale) || locale===activeLocale) return;
  activeLocale=locale;
  try {localStorage.setItem(STORAGE_KEY,locale);} catch (_) {}
  translateStatic();
  document.dispatchEvent(new CustomEvent('atlas:languagechange',{detail:{locale}}));
}
function init() {
  translateStatic();
  for (const select of document.querySelectorAll('[data-language-select]')) {
    select.addEventListener('change',()=>setLocale(select.value));
  }
  window.addEventListener('storage',e=>{if(e.key===STORAGE_KEY && LANGS.includes(e.newValue) && e.newValue!==activeLocale){activeLocale=e.newValue;translateStatic();document.dispatchEvent(new CustomEvent('atlas:languagechange',{detail:{locale:activeLocale}}));}});
}
if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',init);else init();
